use std::collections::HashMap;
use std::path::Path;

use anyhow::{Context, ensure};
use ashpd::desktop::global_shortcuts::GlobalShortcuts;
use ashpd::zbus;
use ashpd::zbus::zvariant::Value;
use log::debug;

const APP_ID: &str = "io.github.Ricky12Awesome.WFFissurePrice";
const GENERATED_ENTRY: &str = "# Generated by wffp-cli for portal registration.\n";

pub async fn init() -> anyhow::Result<()> {
    // GTK_USE_PORTAL only requests portals; it does not give a host application
    // a sandbox identity. ashpd 0.12's register_host_app incorrectly skips
    // registration when that variable is set, so use the Registry directly.
    if Path::new("/.flatpak-info").exists() || std::env::var_os("SNAP").is_some() {
        return Ok(());
    }

    ensure_desktop_entry()?;

    // Constructing this proxy only queries properties, without creating a
    // session. Its connection is the one shared by all subsequent ashpd portals.
    let shortcuts = GlobalShortcuts::new().await?;
    let registry = zbus::Proxy::new(
        shortcuts.connection(),
        "org.freedesktop.portal.Desktop",
        "/org/freedesktop/portal/desktop",
        "org.freedesktop.host.portal.Registry",
    )
    .await?;
    let options: HashMap<&str, Value<'_>> = HashMap::new();
    match registry
        .call::<_, _, ()>("Register", &(APP_ID, options))
        .await
    {
        Ok(()) => debug!("Registered portal application ID: {APP_ID}"),
        // Older portals derive the application identity themselves and do not
        // implement the host Registry interface.
        Err(zbus::Error::MethodError(name, _, _))
            if matches!(
                name.as_str(),
                "org.freedesktop.DBus.Error.UnknownMethod"
                    | "org.freedesktop.DBus.Error.UnknownInterface"
            ) =>
        {
            debug!("Portal host registry is unavailable");
        }
        Err(err) => return Err(err).context("Failed to register the portal application ID"),
    }

    Ok(())
}

fn ensure_desktop_entry() -> anyhow::Result<()> {
    let filename = format!("{APP_ID}.desktop");
    let data_dir = dirs::data_dir().context("Could not locate the application data directory")?;
    let path = data_dir.join("applications").join(&filename);
    let system_dirs = std::env::var_os("XDG_DATA_DIRS")
        .filter(|value| !value.is_empty())
        .unwrap_or_else(|| "/usr/local/share:/usr/share".into());

    // Respect installed desktop entries, but refresh our generated entry if the
    // executable moves (for example, switching from a debug to a release build).
    let existing = match std::fs::read_to_string(&path) {
        Ok(entry) if !entry.starts_with(GENERATED_ENTRY) => return Ok(()),
        Ok(entry) => Some(entry),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
            if std::env::split_paths(&system_dirs)
                .any(|dir| dir.join("applications").join(&filename).exists())
            {
                return Ok(());
            }
            None
        }
        Err(err) => return Err(err).context("Failed to read the portal desktop entry"),
    };

    // Registration requires a real desktop entry even for `cargo run`.
    // Use the absolute executable path because it need not be on PATH.
    let entry = desktop_entry(&std::env::current_exe()?)?;
    if existing.as_ref() == Some(&entry) {
        return Ok(());
    }
    std::fs::create_dir_all(path.parent().unwrap())?;
    std::fs::write(&path, entry)
        .with_context(|| format!("Failed to create portal desktop entry {}", path.display()))?;
    debug!("Created portal desktop entry: {}", path.display());
    Ok(())
}

fn desktop_entry(executable: &Path) -> anyhow::Result<String> {
    let executable = executable
        .to_str()
        .context("The executable path must be valid UTF-8 for its desktop entry")?;
    // GDesktopAppInfo cannot resolve an executable token containing escaped '%'.
    ensure!(
        !executable.contains(['\n', '\r', '=', '%']),
        "The executable path cannot contain newlines, '=' or '%' in its portal desktop entry"
    );
    // Exec quoting is applied after desktop-entry string unescaping.
    let executable = executable
        .replace('\\', "\\\\\\\\")
        .replace('"', "\\\\\"")
        .replace('`', "\\\\`")
        .replace('$', "\\\\$");
    Ok(format!(
        "{GENERATED_ENTRY}[Desktop Entry]\nType=Application\nName=WF Fissure Price\n\
         Comment=Warframe fissure reward price overlay\nExec=\"{executable}\"\n\
         Terminal=true\nNoDisplay=true\nCategories=Game;\n"
    ))
}
